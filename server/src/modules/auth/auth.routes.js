import { Router } from 'express';
import { authenticate } from '../../middleware/authenticate.js';
import { loginRateLimit, registerRateLimit } from '../../middleware/rateLimit.js';
import { validate } from '../../middleware/validate.js';
import * as controller from './auth.controller.js';
import { loginSchema, refreshSchema, registerSchema } from './auth.validator.js';
const router = Router();
router.post('/register', registerRateLimit, validate(registerSchema), controller.register);
router.post('/login', loginRateLimit, validate(loginSchema), controller.login);
router.post('/refresh', validate(refreshSchema), controller.refresh);
router.post('/logout', validate(refreshSchema), controller.logout);
router.get('/me', authenticate, controller.me);
export default router;
